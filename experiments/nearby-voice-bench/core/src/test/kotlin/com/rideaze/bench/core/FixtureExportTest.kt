package com.rideaze.bench.core

import com.rideaze.bench.core.run.Mode
import com.rideaze.bench.core.run.Scenarios
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File

/**
 * Runs full-length (120 s) simulated E1 runs on the fake link and writes the recorder's real JSONL output to
 * build/e2e-fixtures/. analysis/ is then run over these files, which checks that the Kotlin writer and the
 * Python reader agree on the schema. These are SIMULATED results: they say nothing about Nearby.
 */
class FixtureExportTest {
    private val dir = File(System.getProperty("bench.fixtureDir") ?: "build/e2e-fixtures")

    private fun export(sim: Sim) {
        dir.mkdirs()
        File(dir, "${sim.recA.runId}.sender.jsonl").writeText(sim.sinkA.lines.joinToString("\n", postfix = "\n"))
        File(dir, "${sim.recB.runId}.receiver.jsonl").writeText(sim.sinkB.lines.joinToString("\n", postfix = "\n"))
        assertTrue(sim.sender.ledger.violations(true).isEmpty()); assertTrue(sim.reconciliation().violations().isEmpty())
    }

    @Test fun exportSimulatedCampaign() {
        dir.deleteRecursively()
        val rt24 = Scenarios.e1Bytes(24, Mode.REALTIME); val raw24 = Scenarios.e1Bytes(24, Mode.RAW)
        val rt48 = Scenarios.e1Bytes(48, Mode.REALTIME); val rt16 = Scenarios.e1Bytes(16, Mode.REALTIME)
        for (i in 0 until 5) {
            val loss = object : Faults() { override fun lose(kind: Int, seq: Long) = kind == 1 && ((i == 2 && seq % 200 == 7L) || (i == 4 && seq in 3000L..3009L)) }
            export(Sim(rt24, loss, senderRunIndex = i, receiverRunIndex = i, senderEpoch = i, receiverEpoch = i, label = "sim").also { it.run(135_000) })
            export(Sim(raw24, senderRunIndex = i, receiverRunIndex = i, senderEpoch = i, receiverEpoch = i, label = "sim").also { it.run(135_000) })
            val slow = object : Faults() {
                override fun deliverDelayMs(fromSender: Boolean, kind: Int, seq: Long) = if (kind == 1) 260L else 30L
                override fun completionDelayMs(kind: Int, seq: Long) = if (kind == 1) 265L else 35L
            }
            export(Sim(rt48, slow, senderRunIndex = i, receiverRunIndex = i, senderEpoch = i, receiverEpoch = i, label = "sim").also { it.run(135_000) })
        }
        // H4 regression, generated by the real writer: ~1/3 of frames are dropped before submission (window of 2, 60 ms completion)
        // while every SUBMITTED frame arrives on time. Judged against submitted frames this looks perfect; against generated it fails.
        val rt30 = Scenarios.e1Bytes(30, Mode.REALTIME)
        val slowCompletion = object : Faults() { override fun completionDelayMs(kind: Int, seq: Long) = if (kind == 1) 60L else 35L }
        val dropSim = Sim(rt30, slowCompletion, label = "drop").also { it.run(135_000) }
        export(dropSim)
        val dc = dropSim.sender.ledger.counts(); val rc = dropSim.receiver.ledger.counts()
        assertTrue("pre-submission drops should be about a third: ${dc.droppedPre}/${dc.generated}", dc.droppedPre in 1900L..2100L)
        assertEquals("every submitted frame must arrive on time", dc.accepted, rc.byClass.getValue(com.rideaze.bench.core.measure.RxClass.ON_TIME))
        val lost = Sim(rt16, label = "sim").also { s -> s.run(40_000, hook = { t -> if (t == 20_000L) s.linkA.onPeerDisconnected() }) }
        export(lost)
        assertEquals(34, dir.listFiles { f -> f.name.endsWith(".jsonl") }!!.size)
    }
}
